GRANT ALL ON TABLE public.perfil_gear TO authenticated;
GRANT ALL ON TABLE public.perfil_gear TO service_role;
GRANT ALL ON TABLE public.generos_perfil TO authenticated;
GRANT ALL ON TABLE public.generos_perfil TO service_role;

